create or replace function public.complete_sale(
  p_customer_name text,
  p_payment_type text,
  p_payment double precision,
  p_cart jsonb,
  p_request_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  existing_id bigint;
  transaction_id bigint;
  invoice_number text;
  item jsonb;
  product_row public.products%rowtype;
  item_qty integer;
  requested_unit text;
  base_factor integer;
  sale_factor integer;
  stock_deduction integer;
  sale_price double precision;
  sale_unit_price double precision;
  sale_cost double precision;
  sale_total double precision := 0;
  next_stock_cost_value double precision;
  saved_items jsonb := '[]'::jsonb;
  initial_payment double precision;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if nullif(trim(p_customer_name), '') is null then raise exception 'Nama pelanggan wajib diisi.'; end if;
  if p_payment_type is null or p_payment_type not in ('cash', 'credit') then
    raise exception 'Metode pembayaran tidak valid.';
  end if;
  if p_payment is null or p_payment < 0 then raise exception 'Nominal pembayaran tidak valid.'; end if;
  if p_request_id is null then raise exception 'ID permintaan transaksi wajib diisi.'; end if;
  if p_cart is null or jsonb_typeof(p_cart) <> 'array' then
    raise exception 'Keranjang masih kosong.';
  end if;
  if jsonb_array_length(p_cart) = 0 then raise exception 'Keranjang masih kosong.'; end if;

  select id into existing_id
  from public.transactions
  where owner_id = current_user_id and "requestId" = p_request_id;
  if existing_id is not null then return existing_id; end if;

  for item in select value from jsonb_array_elements(p_cart)
  loop
    if coalesce(item ->> 'qty', '') !~ '^[0-9]+$' then
      raise exception 'Jumlah barang tidak valid.';
    end if;
    item_qty := (item ->> 'qty')::integer;
    if item_qty <= 0 then raise exception 'Jumlah barang tidak valid.'; end if;

    select * into product_row
    from public.products
    where id = (item ->> 'productId')::bigint and owner_id = current_user_id
    for update;
    if not found then raise exception 'Produk tidak ditemukan atau tidak dapat diakses.'; end if;
    requested_unit := lower(trim(coalesce(item ->> 'unit', product_row.unit)));
    base_factor := public.product_unit_factor(product_row.unit);
    sale_factor := public.product_unit_factor(requested_unit);
    if lower(trim(product_row.unit)) not in ('pcs', 'lusin', 'kodi')
       and requested_unit <> lower(trim(product_row.unit)) then
      raise exception 'Satuan transaksi untuk "%" tidak valid.', product_row.name;
    end if;
    if lower(trim(product_row.unit)) in ('pcs', 'lusin', 'kodi')
       and requested_unit not in ('pcs', 'lusin', 'kodi') then
      raise exception 'Satuan transaksi untuk "%" tidak valid.', product_row.name;
    end if;
    stock_deduction := item_qty * sale_factor;
    if product_row.stock_pcs < stock_deduction then
      raise exception 'Stok "%" tidak cukup untuk dijual per %.', product_row.name, requested_unit;
    end if;
    sale_price := case requested_unit
      when 'pcs' then product_row.price_pcs
      when 'lusin' then product_row.price_lusin
      when 'kodi' then product_row.price_kodi
      else product_row.price
    end;
    if sale_price <= 0 then
      raise exception 'Harga jual per % untuk "%" belum diatur.', requested_unit, product_row.name;
    end if;
    sale_unit_price := sale_price * sale_factor;
    if sale_unit_price is distinct from (item ->> 'price')::double precision then
      raise exception 'Harga produk "%" berubah. Muat ulang halaman sebelum menyimpan.', product_row.name;
    end if;

    sale_cost := case
      when product_row.stock_pcs > 0
        then coalesce(product_row.stock_cost_value, product_row.cost * product_row.stock_pcs)
          / product_row.stock_pcs * sale_factor
      else product_row.cost * sale_factor
    end;
    sale_total := sale_total + sale_unit_price * item_qty;
    next_stock_cost_value := greatest(
      0,
      coalesce(product_row.stock_cost_value, product_row.cost * product_row.stock_pcs)
        - sale_cost * item_qty
    );
    saved_items := saved_items || jsonb_build_array(jsonb_build_object(
      'productId', product_row.id,
      'name', product_row.name,
      'unit', requested_unit,
      'price', sale_unit_price,
      'cost', sale_cost,
      'qty', item_qty
    ));
    update public.products
    set stock_pcs = stock_pcs - stock_deduction,
        stock = (stock_pcs - stock_deduction)::double precision / base_factor,
        stock_cost_value = next_stock_cost_value,
        cost = case
          when stock_pcs - stock_deduction > 0
            then next_stock_cost_value / (stock_pcs - stock_deduction)
          else cost
        end,
        "updatedAt" = operation_time
    where id = product_row.id and owner_id = current_user_id;
  end loop;

  if p_payment_type = 'cash' and p_payment < sale_total then
    raise exception 'Uang tunai kurang dari total belanja.';
  end if;
  if p_payment_type = 'credit' and p_payment > sale_total then
    raise exception 'Pembayaran awal melebihi total belanja.';
  end if;

  initial_payment := case when p_payment_type = 'cash' then sale_total else p_payment end;
  insert into public.transactions (
    owner_id, items, total, payment, "customerName", "paymentType",
    "paidAmount", "balanceDue", payments, "change", "requestId", "createdAt", "updatedAt"
  ) values (
    current_user_id, saved_items, sale_total, p_payment, trim(p_customer_name), p_payment_type,
    initial_payment, sale_total - initial_payment,
    case when p_payment_type = 'credit' and initial_payment > 0
      then jsonb_build_array(jsonb_build_object('amount', initial_payment, 'date', operation_time))
      else '[]'::jsonb end,
    case when p_payment_type = 'cash' then p_payment - sale_total else 0 end,
    p_request_id, operation_time, operation_time
  ) returning id into transaction_id;

  invoice_number := 'INV-' || to_char(operation_time at time zone 'Asia/Jakarta', 'YYYYMMDD')
    || '-' || lpad(transaction_id::text, 2, '0');
  update public.transactions set "invoiceNo" = invoice_number where id = transaction_id;

  if initial_payment > 0 then
    insert into public.finance_entries (
      owner_id, type, category, note, amount, "refId", date, "createdAt", "updatedAt"
    ) values (
      current_user_id, 'income',
      case when p_payment_type = 'credit' then 'DP kredit' else 'Penjualan' end,
      'Penjualan · ' || trim(p_customer_name), initial_payment, transaction_id,
      operation_time, operation_time, operation_time
    );
  end if;

  return transaction_id;
end;
$$;

create or replace function public.record_transaction_payment(
  p_transaction_id bigint,
  p_amount double precision,
  p_request_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  transaction_row public.transactions%rowtype;
  existing_ref bigint;
  new_paid_amount double precision;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_request_id is null then raise exception 'ID permintaan pembayaran wajib diisi.'; end if;
  select * into transaction_row
  from public.transactions
  where id = p_transaction_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Transaksi tidak ditemukan.'; end if;

  select "refId" into existing_ref from public.finance_entries
  where owner_id = current_user_id and "requestId" = p_request_id;
  if existing_ref is not null then
    if existing_ref <> p_transaction_id then raise exception 'ID permintaan pembayaran sudah digunakan.'; end if;
    return existing_ref;
  end if;
  if transaction_row."paymentType" <> 'credit' then
    raise exception 'Cicilan hanya dapat dicatat untuk transaksi kredit.';
  end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Nominal cicilan harus lebih dari Rp0.'; end if;
  if p_amount > transaction_row."balanceDue" then
    raise exception 'Nominal cicilan melebihi sisa utang.';
  end if;

  new_paid_amount := transaction_row."paidAmount" + p_amount;
  update public.transactions
  set "paidAmount" = new_paid_amount,
      "balanceDue" = greatest(0, total - new_paid_amount),
      payments = payments || jsonb_build_array(jsonb_build_object('amount', p_amount, 'date', operation_time)),
      "updatedAt" = operation_time
  where id = p_transaction_id;

  insert into public.finance_entries (
    owner_id, type, category, note, amount, "refId", "requestId", date, "createdAt", "updatedAt"
  ) values (
    current_user_id, 'income', 'Cicilan kredit',
    'Cicilan transaksi ' || coalesce(transaction_row."invoiceNo", '#' || p_transaction_id::text)
      || ' · ' || transaction_row."customerName",
    p_amount, p_transaction_id, p_request_id, operation_time, operation_time, operation_time
  );

  return p_transaction_id;
end;
$$;

create or replace function public.delete_manual_finance_entry(p_entry_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  entry_row public.finance_entries%rowtype;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;

  select * into entry_row
  from public.finance_entries
  where id = p_entry_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Catatan keuangan tidak ditemukan.'; end if;

  if entry_row."refId" is not null
     or entry_row."requestId" is not null
     or lower(trim(coalesce(entry_row.category, ''))) in ('penjualan', 'dp kredit', 'cicilan kredit')
     or coalesce(entry_row.note, '') like 'Penjualan ·%'
     or coalesce(entry_row.note, '') like 'Cicilan transaksi %' then
    raise exception 'Catatan yang berasal dari transaksi tidak dapat dihapus dari buku kas.';
  end if;

  delete from public.finance_entries
  where id = p_entry_id and owner_id = current_user_id;
end;
$$;

create or replace function public.get_transaction_summary(
  p_from timestamptz,
  p_to timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  result_count bigint;
  result_total numeric;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_from is not null and p_to is not null and p_from >= p_to then
    raise exception 'Rentang tanggal tidak valid.';
  end if;

  select count(*), coalesce(sum(t.total), 0)
  into result_count, result_total
  from public.transactions t
  where t.owner_id = current_user_id
    and (p_from is null or t."createdAt" >= p_from)
    and (p_to is null or t."createdAt" < p_to);

  return jsonb_build_object(
    'transaction_count', result_count,
    'total', result_total
  );
end;
$$;

create or replace function public.get_dashboard_data(
  p_from timestamptz,
  p_to timestamptz,
  p_summary_from timestamptz,
  p_summary_to timestamptz,
  p_page integer,
  p_page_size integer,
  p_credit_first boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  result_count bigint;
  summary_count bigint;
  revenue_total numeric;
  gross_profit numeric;
  transaction_rows jsonb;
  inventory_summary jsonb;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_page is null or p_page < 1 or p_page_size is null or p_page_size < 1 or p_page_size > 100 then
    raise exception 'Halaman transaksi tidak valid.';
  end if;
  if (p_from is not null and p_to is not null and p_from >= p_to)
     or (p_summary_from is not null and p_summary_to is not null and p_summary_from >= p_summary_to) then
    raise exception 'Rentang tanggal tidak valid.';
  end if;

  select count(*), coalesce(sum(t.total), 0),
    coalesce(sum((
      select coalesce(sum(
        (coalesce(nullif(item.value ->> 'price', '')::numeric, 0)
          - coalesce(nullif(item.value ->> 'cost', '')::numeric, 0))
        * coalesce(nullif(item.value ->> 'qty', '')::numeric, 0)
      ), 0)
      from jsonb_array_elements(coalesce(t.items, '[]'::jsonb)) as item(value)
    )), 0)
  into summary_count, revenue_total, gross_profit
  from public.transactions t
  where t.owner_id = current_user_id
    and (p_summary_from is null or t."createdAt" >= p_summary_from)
    and (p_summary_to is null or t."createdAt" < p_summary_to);

  select count(*)
  into result_count
  from public.transactions t
  where t.owner_id = current_user_id
    and (p_from is null or t."createdAt" >= p_from)
    and (p_to is null or t."createdAt" < p_to);

  select jsonb_build_object(
    'product_count', count(*),
    'low_stock_count', count(*) filter (
      where floor(p.stock_pcs::numeric / public.product_unit_factor(p.unit)) <= 5
    ),
    'total_asset', coalesce(sum(p.stock_cost_value), 0)
  )
  into inventory_summary
  from public.products p
  where p.owner_id = current_user_id;

  select coalesce(jsonb_agg(to_jsonb(page_rows) - 'sort_rank'
    order by page_rows.sort_rank, page_rows."createdAt" desc nulls last, page_rows.id desc), '[]'::jsonb)
  into transaction_rows
  from (
    select t.*,
      case
        when coalesce(p_credit_first, false)
          and t."paymentType" = 'credit'
          and greatest(0, coalesce(t."balanceDue", t.total - coalesce(t."paidAmount", t.payment))) > 0
        then 0 else 1
      end as sort_rank
    from public.transactions t
    where t.owner_id = current_user_id
      and (p_from is null or t."createdAt" >= p_from)
      and (p_to is null or t."createdAt" < p_to)
    order by sort_rank, t."createdAt" desc nulls last, t.id desc
    limit p_page_size offset (p_page - 1) * p_page_size
  ) as page_rows;

  return jsonb_build_object(
    'transactions', transaction_rows,
    'total_count', result_count,
    'summary_count', summary_count,
    'revenue', revenue_total,
    'gross_profit', gross_profit,
    'inventory', inventory_summary
  );
end;
$$;

create or replace function public.get_finance_data(
  p_from timestamptz,
  p_to timestamptz,
  p_page integer,
  p_page_size integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  entry_count bigint;
  entries jsonb;
  income_total numeric;
  expense_total numeric;
  capital_total numeric;
  credit_total numeric;
  credit_balances jsonb;
  gross_profit numeric;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_page is null or p_page < 1 or p_page_size is null or p_page_size < 1 or p_page_size > 100 then
    raise exception 'Halaman buku kas tidak valid.';
  end if;
  if p_from is not null and p_to is not null and p_from >= p_to then
    raise exception 'Rentang tanggal tidak valid.';
  end if;

  select count(*),
    coalesce(sum(e.amount) filter (where e.type = 'income'), 0),
    coalesce(sum(e.amount) filter (where e.type = 'expense'), 0),
    coalesce(sum(e.amount) filter (where e.type = 'capital'), 0)
  into entry_count, income_total, expense_total, capital_total
  from public.finance_entries e
  where e.owner_id = current_user_id
    and (p_from is null or coalesce(e.date, e."createdAt") >= p_from)
    and (p_to is null or coalesce(e.date, e."createdAt") < p_to);

  select coalesce(sum(greatest(0, coalesce(t."balanceDue", t.total - coalesce(t."paidAmount", t.payment)))), 0)
  into credit_total
  from public.transactions t
  where t.owner_id = current_user_id and t."paymentType" = 'credit';

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'customer_name', debt.customer_name,
      'balance_due', debt.balance_due
    ) order by debt.balance_due desc, debt.customer_name
  ), '[]'::jsonb)
  into credit_balances
  from (
    select
      coalesce(nullif(btrim(t."customerName"), ''), 'Pelanggan lama') as customer_name,
      sum(greatest(0, coalesce(t."balanceDue", t.total - coalesce(t."paidAmount", t.payment)))) as balance_due
    from public.transactions t
    where t.owner_id = current_user_id and t."paymentType" = 'credit'
    group by coalesce(nullif(btrim(t."customerName"), ''), 'Pelanggan lama')
    having sum(greatest(0, coalesce(t."balanceDue", t.total - coalesce(t."paidAmount", t.payment)))) > 0
  ) as debt;

  select coalesce(sum((
    select coalesce(sum(
      (coalesce(nullif(item.value ->> 'price', '')::numeric, 0)
        - coalesce(nullif(item.value ->> 'cost', '')::numeric, 0))
      * coalesce(nullif(item.value ->> 'qty', '')::numeric, 0)
    ), 0)
    from jsonb_array_elements(coalesce(t.items, '[]'::jsonb)) as item(value)
  )), 0)
  into gross_profit
  from public.transactions t
  where t.owner_id = current_user_id
    and (p_from is null or t."createdAt" >= p_from)
    and (p_to is null or t."createdAt" < p_to);

  select coalesce(jsonb_agg(to_jsonb(page_rows)
    order by coalesce(page_rows.date, page_rows."createdAt") desc nulls last, page_rows.id desc), '[]'::jsonb)
  into entries
  from (
    select e.*
    from public.finance_entries e
    where e.owner_id = current_user_id
      and (p_from is null or coalesce(e.date, e."createdAt") >= p_from)
      and (p_to is null or coalesce(e.date, e."createdAt") < p_to)
    order by coalesce(e.date, e."createdAt") desc nulls last, e.id desc
    limit p_page_size offset (p_page - 1) * p_page_size
  ) as page_rows;

  return jsonb_build_object(
    'entries', entries,
    'total_count', entry_count,
    'income', income_total,
    'expense', expense_total,
    'capital', capital_total,
    'total_credit', credit_total,
    'credit_balances', credit_balances,
    'gross_profit', gross_profit
  );
end;
$$;

