create or replace function public.complete_sale(
  p_customer_name text,
  p_payment_type text,
  p_payment double precision,
  p_cart jsonb,
  p_expedition text,
  p_request_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  existing_id bigint;
  transaction_id bigint;
  invoice_number text;
  invoice_date text;
  invoice_sequence bigint;
  item jsonb;
  product_row public.products%rowtype;
  item_qty integer;
  requested_unit text;
  base_factor integer;
  sale_factor integer;
  stock_deduction integer;
  sale_price double precision;
  sale_unit_price double precision;
  sale_cost double precision;
  sale_total double precision := 0;
  next_stock_cost_value double precision;
  saved_items jsonb := '[]'::jsonb;
  initial_payment double precision;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if nullif(trim(p_customer_name), '') is null then raise exception 'Nama pelanggan wajib diisi.'; end if;
  if p_payment_type is null or p_payment_type not in ('cash', 'credit') then
    raise exception 'Metode pembayaran tidak valid.';
  end if;
  if p_payment is null or p_payment < 0
     or p_payment > 9007199254740991::double precision
     or p_payment <> trunc(p_payment)
     or p_payment::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Nominal pembayaran harus rupiah utuh dalam batas aman.';
  end if;
  if p_request_id is null then raise exception 'ID permintaan transaksi wajib diisi.'; end if;
  if p_cart is null or jsonb_typeof(p_cart) <> 'array' then
    raise exception 'Keranjang masih kosong.';
  end if;
  if jsonb_array_length(p_cart) = 0 then raise exception 'Keranjang masih kosong.'; end if;

  invoice_date := to_char(operation_time at time zone 'Asia/Jakarta', 'YYYYMMDD');
  perform pg_advisory_xact_lock(hashtextextended(current_user_id::text, 0));

  select id into existing_id
  from public.transactions
  where owner_id = current_user_id and "requestId" = p_request_id;
  if existing_id is not null then return existing_id; end if;

  if nullif(trim(coalesce(p_expedition, '')), '') is not null
    and not exists (
      select 1 from public.expedition_names
      where owner_id = current_user_id and name = trim(p_expedition)
    ) then
    raise exception 'Pilih ekspedisi yang masih tersedia dari tab Setting.';
  end if;

  for item in select value from jsonb_array_elements(p_cart)
  loop
    if coalesce(item ->> 'qty', '') !~ '^[0-9]+$' then
      raise exception 'Jumlah barang tidak valid.';
    end if;
    item_qty := (item ->> 'qty')::integer;
    if item_qty <= 0 then raise exception 'Jumlah barang tidak valid.'; end if;

    select * into product_row
    from public.products
    where id = (item ->> 'productId')::bigint and owner_id = current_user_id
    for update;
    if not found then raise exception 'Produk tidak ditemukan atau tidak dapat diakses.'; end if;
    requested_unit := lower(trim(coalesce(item ->> 'unit', product_row.unit)));
    base_factor := public.product_unit_factor(product_row.unit);
    sale_factor := public.product_unit_factor(requested_unit);
    if lower(trim(product_row.unit)) not in ('pcs', 'lusin')
       and requested_unit <> lower(trim(product_row.unit)) then
      raise exception 'Satuan transaksi untuk "%" tidak valid.', product_row.name;
    end if;
    if lower(trim(product_row.unit)) in ('pcs', 'lusin')
       and requested_unit not in ('pcs', 'lusin') then
      raise exception 'Satuan transaksi untuk "%" tidak valid.', product_row.name;
    end if;
    stock_deduction := item_qty * sale_factor;
    if product_row.stock_pcs < stock_deduction then
      raise exception 'Stok "%" tidak cukup untuk dijual per %.', product_row.name, requested_unit;
    end if;
    sale_price := case requested_unit
      when 'pcs' then case
        when product_row.price_pcs > 0 then product_row.price_pcs
        when product_row.sale_markup_pcs_pct is not null and product_row.cost > 0
          then round((product_row.cost * (100 + product_row.sale_markup_pcs_pct) / 100)::numeric)::double precision
        else product_row.price_pcs
      end
      when 'lusin' then case
        when product_row.price_lusin > 0 then product_row.price_lusin
        when product_row.sale_markup_lusin_pct is not null and product_row.cost > 0
          then round((product_row.cost * 12 * (100 + product_row.sale_markup_lusin_pct) / 100)::numeric)::double precision
        else product_row.price_lusin
      end
      else product_row.price
    end;
    if sale_price <= 0 then
      raise exception 'Harga jual per % untuk "%" belum diatur.', requested_unit, product_row.name;
    end if;
    sale_unit_price := sale_price;
    if sale_unit_price is distinct from (item ->> 'price')::double precision then
      raise exception 'Harga produk "%" berubah. Muat ulang halaman sebelum menyimpan.', product_row.name;
    end if;

    sale_cost := case
      when product_row.stock_pcs > 0
        then coalesce(product_row.stock_cost_value, product_row.cost * product_row.stock_pcs)
          / product_row.stock_pcs * sale_factor
      else product_row.cost * sale_factor
    end;
    sale_total := sale_total + sale_unit_price * item_qty;
    next_stock_cost_value := greatest(
      0,
      coalesce(product_row.stock_cost_value, product_row.cost * product_row.stock_pcs)
        - sale_cost * item_qty
    );
    saved_items := saved_items || jsonb_build_array(jsonb_build_object(
      'productId', product_row.id,
      'name', product_row.name,
      'unit', requested_unit,
      'price', sale_unit_price,
      'cost', sale_cost,
      'qty', item_qty
    ));
    update public.products
    set stock_pcs = stock_pcs - stock_deduction,
        stock = (stock_pcs - stock_deduction)::double precision / base_factor,
        stock_cost_value = next_stock_cost_value,
        cost = case
          when stock_pcs - stock_deduction > 0
            then next_stock_cost_value / (stock_pcs - stock_deduction)
          else cost
        end,
        "updatedAt" = operation_time
    where id = product_row.id and owner_id = current_user_id;
  end loop;

  if sale_total <= 0
     or sale_total > 9007199254740991::double precision
     or sale_total <> trunc(sale_total)
     or sale_total::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Total transaksi melebihi batas nominal rupiah yang aman.';
  end if;

  if p_payment_type = 'cash' and p_payment < sale_total then
    raise exception 'Uang tunai kurang dari total belanja.';
  end if;
  if p_payment_type = 'credit' and p_payment > sale_total then
    raise exception 'Pembayaran awal melebihi total belanja.';
  end if;

  initial_payment := case when p_payment_type = 'cash' then sale_total else p_payment end;
  insert into public.transactions (
    owner_id, items, total, payment, "customerName", expedition, "paymentType",
    "paidAmount", "balanceDue", payments, "change", "requestId", "createdAt", "updatedAt"
  ) values (
    current_user_id, saved_items, sale_total, p_payment, trim(p_customer_name), trim(coalesce(p_expedition, '')), p_payment_type,
    initial_payment, sale_total - initial_payment,
    case when p_payment_type = 'credit' and initial_payment > 0
      then jsonb_build_array(jsonb_build_object('amount', initial_payment, 'date', operation_time))
      else '[]'::jsonb end,
    case when p_payment_type = 'cash' then p_payment - sale_total else 0 end,
    p_request_id, operation_time, operation_time
  ) returning id into transaction_id;

  if p_payment_type = 'credit' and initial_payment > 0 then
    insert into public.transaction_payments (
      owner_id, transaction_id, amount, date, source
    ) values (
      current_user_id, transaction_id, initial_payment, operation_time, 'initial'
    );
  end if;

  select coalesce(max(substring("invoiceNo" from ('^INV-' || invoice_date || '-([0-9]+)$'))::bigint), 0) + 1
    into invoice_sequence
  from public.transactions
  where owner_id = current_user_id
    and "invoiceNo" like ('INV-' || invoice_date || '-%')
    and "invoiceNo" ~ ('^INV-' || invoice_date || '-[0-9]+$');

  invoice_number := 'INV-' || invoice_date || '-' || lpad(invoice_sequence::text, 2, '0');
  update public.transactions set "invoiceNo" = invoice_number where id = transaction_id;

  if initial_payment > 0 then
    insert into public.finance_entries (
      owner_id, type, category, note, amount, "refId", date, "createdAt", "updatedAt"
    ) values (
      current_user_id, 'income',
      case when p_payment_type = 'credit' then 'DP kredit' else 'Penjualan' end,
      'Penjualan · ' || trim(p_customer_name), initial_payment, transaction_id,
      operation_time, operation_time, operation_time
    );
  end if;

  if nullif(trim(coalesce(p_expedition, '')), '') is not null then
    insert into public.finance_entries (
      owner_id, type, category, note, amount, pending, "refId", date, "createdAt", "updatedAt"
    ) values (
      current_user_id, 'expense',
      'Biaya Ekspedisi ' || trim(p_expedition) || ' ('
        || coalesce(nullif(trim(p_customer_name), ''), 'Pelanggan') || ')',
      'Ekspedisi ' || trim(p_expedition) || ' · ' || invoice_number,
      0, true, transaction_id, operation_time, operation_time, operation_time
    );
  end if;

  return transaction_id;
end;
$$;

create or replace function public.return_transaction_items(
  p_transaction_id bigint,
  p_items jsonb,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  transaction_row public.transactions%rowtype;
  product_row public.products%rowtype;
  requested_line jsonb;
  original_item jsonb;
  previous_event jsonb;
  returned_event jsonb;
  returned_items jsonb := '[]'::jsonb;
  line_index integer;
  requested_qty integer;
  original_qty integer;
  already_returned bigint;
  product_id bigint;
  stock_add bigint;
  current_stock_value double precision;
  item_cost double precision;
  item_price numeric;
  returned_amount numeric := 0;
  new_total double precision;
  old_paid_amount double precision;
  new_paid_amount double precision;
  refund_amount double precision;
  new_balance_due double precision;
  returned_profit double precision := 0;
  new_gross_profit double precision;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_transaction_id is null then raise exception 'Transaksi tidak valid.'; end if;
  if p_request_id is null then raise exception 'ID permintaan retur wajib diisi.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0
     or jsonb_array_length(p_items) > 100 then
    raise exception 'Daftar barang retur tidak valid.';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_items) as input(value)
    where coalesce(value ->> 'lineIndex', '') !~ '^[0-9]+$'
       or coalesce(value ->> 'qty', '') !~ '^[0-9]+$'
  ) then
    raise exception 'Baris atau jumlah barang retur tidak valid.';
  end if;
  if (
    select count(*) <> count(distinct value ->> 'lineIndex')
    from jsonb_array_elements(p_items) as input(value)
  ) then
    raise exception 'Setiap barang hanya boleh muncul satu kali dalam satu retur.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(current_user_id::text || p_request_id::text, 0));
  select * into transaction_row
  from public.transactions
  where id = p_transaction_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Transaksi tidak ditemukan atau tidak dapat diakses.'; end if;

  select event.value into previous_event
  from jsonb_array_elements(coalesce(transaction_row.returns, '[]'::jsonb)) as event(value)
  where event.value ->> 'requestId' = p_request_id::text
  limit 1;
  if previous_event is not null then
    if previous_event -> 'requestedItems' is distinct from p_items then
      raise exception 'ID permintaan retur sudah digunakan.';
    end if;
    return previous_event;
  end if;

  for requested_line in
    select input.value
    from jsonb_array_elements(p_items) as input(value)
    order by (
      (transaction_row.items -> ((input.value ->> 'lineIndex')::integer) ->> 'productId')::bigint
    ), (input.value ->> 'lineIndex')::integer
  loop
    line_index := (requested_line ->> 'lineIndex')::integer;
    requested_qty := (requested_line ->> 'qty')::integer;
    if requested_qty <= 0 then raise exception 'Jumlah barang retur harus lebih dari nol.'; end if;
    original_item := transaction_row.items -> line_index;
    if original_item is null or jsonb_typeof(original_item) <> 'object' then
      raise exception 'Barang transaksi yang dipilih tidak ditemukan.';
    end if;
    if coalesce(original_item ->> 'qty', '') !~ '^[0-9]+$'
       or coalesce(original_item ->> 'productId', '') !~ '^[0-9]+$' then
      raise exception 'Data barang transaksi tidak mendukung retur.';
    end if;
    original_qty := (original_item ->> 'qty')::integer;
    product_id := (original_item ->> 'productId')::bigint;
    if coalesce(original_item ->> 'price', '') !~ '^[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$' then
      raise exception 'Harga barang transaksi tidak valid untuk retur.';
    end if;
    item_price := (original_item ->> 'price')::numeric;
    if item_price <= 0 or item_price <> trunc(item_price)
       or item_price > 9007199254740991 then
      raise exception 'Harga barang transaksi tidak valid untuk retur.';
    end if;

    select coalesce(sum((returned_item.value ->> 'qty')::bigint), 0)
    into already_returned
    from jsonb_array_elements(coalesce(transaction_row.returns, '[]'::jsonb)) as prior(value)
    cross join lateral jsonb_array_elements(coalesce(prior.value -> 'items', '[]'::jsonb)) as returned_item(value)
    where (returned_item.value ->> 'lineIndex')::integer = line_index;
    if already_returned + requested_qty > original_qty then
      raise exception 'Jumlah retur melebihi sisa barang pada transaksi.';
    end if;

    select * into product_row
    from public.products
    where id = product_id and owner_id = current_user_id
    for update;
    if not found then
      raise exception 'Produk "%" sudah tidak tersedia di katalog; retur tidak dapat menambah stok.', original_item ->> 'name';
    end if;

    stock_add := requested_qty::bigint * public.product_unit_factor(original_item ->> 'unit');
    if product_row.stock_pcs::bigint + stock_add > 2147483647 then
      raise exception 'Stok produk "%" melebihi batas penyimpanan.', product_row.name;
    end if;
    item_cost := coalesce(
      (original_item ->> 'cost')::double precision,
      product_row.cost * public.product_unit_factor(original_item ->> 'unit')
    );
    if item_cost < 0 or item_cost::text in ('NaN', 'Infinity', '-Infinity') then
      raise exception 'Modal historis produk "%" tidak valid untuk retur.', product_row.name;
    end if;
    current_stock_value := coalesce(product_row.stock_cost_value, product_row.cost * product_row.stock_pcs)
      + item_cost * requested_qty;
    if current_stock_value::text in ('NaN', 'Infinity', '-Infinity') then
      raise exception 'Nilai modal stok produk "%" melebihi batas penyimpanan.', product_row.name;
    end if;

    update public.products
    set stock_pcs = product_row.stock_pcs + stock_add::integer,
        stock = (product_row.stock_pcs + stock_add)::double precision
          / public.product_unit_factor(product_row.unit),
        stock_cost_value = current_stock_value,
        cost = case when product_row.stock_pcs + stock_add > 0
          then current_stock_value / (product_row.stock_pcs + stock_add)
          else product_row.cost
        end,
        "updatedAt" = operation_time
    where id = product_id and owner_id = current_user_id;

    returned_amount := returned_amount
      + item_price * requested_qty;
    returned_profit := returned_profit
      + (item_price::double precision - item_cost) * requested_qty;
    returned_items := returned_items || jsonb_build_array(jsonb_build_object(
      'lineIndex', line_index,
      'productId', product_id,
      'name', original_item ->> 'name',
      'unit', original_item ->> 'unit',
      'qty', requested_qty,
      'price', item_price::double precision,
      'cost', item_cost
    ));
  end loop;

  if returned_amount <= 0 or returned_amount <> trunc(returned_amount)
     or returned_amount > 9007199254740991 then
    raise exception 'Nilai retur melebihi batas nominal rupiah yang aman.';
  end if;
  if returned_amount > transaction_row.total then
    raise exception 'Nilai retur melebihi sisa nilai transaksi.';
  end if;

  new_total := transaction_row.total - returned_amount::double precision;
  old_paid_amount := coalesce(transaction_row."paidAmount", transaction_row.payment);
  if transaction_row.total < 0
     or transaction_row.total::text in ('NaN', 'Infinity', '-Infinity')
     or old_paid_amount < 0
     or old_paid_amount::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Nilai pembayaran transaksi tidak valid untuk retur.';
  end if;
  refund_amount := greatest(0, old_paid_amount - new_total);
  new_paid_amount := old_paid_amount - refund_amount;
  new_balance_due := greatest(0, new_total - new_paid_amount);
  new_gross_profit := coalesce(transaction_row.gross_profit, 0) - returned_profit;
  returned_event := jsonb_build_object(
    'requestId', p_request_id,
    'date', operation_time,
    'requestedItems', p_items,
    'items', returned_items,
    'amount', returned_amount,
    'refundAmount', refund_amount,
    'total', new_total,
    'paidAmount', new_paid_amount,
    'balanceDue', new_balance_due
  );

  update public.transactions
  set total = new_total,
      "paidAmount" = new_paid_amount,
      "balanceDue" = new_balance_due,
      gross_profit = new_gross_profit,
      returns = coalesce(returns, '[]'::jsonb) || jsonb_build_array(returned_event),
      "updatedAt" = operation_time
  where id = p_transaction_id and owner_id = current_user_id;

  if refund_amount > 0 then
    insert into public.finance_entries (
      owner_id, type, category, note, amount, "refId", "requestId", date, "createdAt", "updatedAt"
    ) values (
      current_user_id,
      'expense',
      'Refund Retur Penjualan',
      'Refund retur · ' || coalesce(nullif(transaction_row."invoiceNo", ''), 'Transaksi #' || p_transaction_id::text)
        || ' · ' || coalesce(nullif(transaction_row."customerName", ''), 'Pelanggan'),
      refund_amount,
      p_transaction_id,
      p_request_id,
      operation_time,
      operation_time,
      operation_time
    );
  end if;

  return returned_event;
end;
$$;

create or replace function public.record_transaction_payment(
  p_transaction_id bigint,
  p_amount double precision,
  p_request_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  transaction_row public.transactions%rowtype;
  existing_ref bigint;
  new_paid_amount double precision;
  customer_balance double precision;
  existing_customer_payments double precision;
  target_customer_name text;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_request_id is null then raise exception 'ID permintaan pembayaran wajib diisi.'; end if;

  select coalesce(nullif(btrim("customerName"), ''), 'Pelanggan lama')
  into target_customer_name
  from public.transactions
  where id = p_transaction_id and owner_id = current_user_id;
  if not found then raise exception 'Transaksi tidak ditemukan.'; end if;

  perform pg_advisory_xact_lock(hashtextextended(
    current_user_id::text || lower(btrim(target_customer_name)),
    1
  ));

  select * into transaction_row
  from public.transactions
  where id = p_transaction_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Transaksi tidak ditemukan.'; end if;

  select "refId" into existing_ref from public.finance_entries
  where owner_id = current_user_id and "requestId" = p_request_id;
  if existing_ref is not null then
    if existing_ref <> p_transaction_id then raise exception 'ID permintaan pembayaran sudah digunakan.'; end if;
    return existing_ref;
  end if;
  if transaction_row."paymentType" <> 'credit' then
    raise exception 'Cicilan hanya dapat dicatat untuk transaksi kredit.';
  end if;
  if p_amount is null or p_amount <= 0
     or p_amount > 9007199254740991::double precision
     or p_amount <> trunc(p_amount)
     or p_amount::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Nominal cicilan harus rupiah utuh dalam batas aman.';
  end if;
  if p_amount > transaction_row."balanceDue" then
    raise exception 'Nominal cicilan melebihi sisa utang.';
  end if;

  select coalesce(sum(outstanding.balance_due), 0)
  into customer_balance
  from (
    select credit.balance_due
    from public.manual_customer_credits as credit
    where credit.owner_id = current_user_id
      and lower(btrim(credit.customer_name)) = lower(btrim(target_customer_name))
      and credit.balance_due > 0
    union all
    select customer_transaction."balanceDue"
    from public.transactions as customer_transaction
    where customer_transaction.owner_id = current_user_id
      and customer_transaction."paymentType" = 'credit'
      and lower(coalesce(nullif(btrim(customer_transaction."customerName"), ''), 'Pelanggan lama'))
        = lower(btrim(target_customer_name))
      and customer_transaction."balanceDue" > 0
  ) as outstanding;

  select coalesce(sum(entry.amount), 0)
  into existing_customer_payments
  from public.finance_entries as entry
  where entry.owner_id = current_user_id
    and entry.type = 'income'
    and entry.category = 'Cicilan kredit'
    and left(entry.note, char_length('Pembayaran umum piutang pelanggan · '))
      = 'Pembayaran umum piutang pelanggan · '
    and lower(btrim(substring(
      entry.note from char_length('Pembayaran umum piutang pelanggan · ') + 1
    ))) = lower(btrim(target_customer_name));

  if p_amount > greatest(0, customer_balance - existing_customer_payments) then
    raise exception 'Nominal cicilan melebihi sisa piutang gabungan pelanggan.';
  end if;

  new_paid_amount := transaction_row."paidAmount" + p_amount;
  update public.transactions
  set "paidAmount" = new_paid_amount,
      "balanceDue" = greatest(0, total - new_paid_amount),
      "updatedAt" = operation_time
  where id = p_transaction_id;

  insert into public.transaction_payments (
    owner_id, transaction_id, amount, date, source
  ) values (
    current_user_id, p_transaction_id, p_amount, operation_time, 'installment'
  );

  insert into public.finance_entries (
    owner_id, type, category, note, amount, "refId", "requestId", date, "createdAt", "updatedAt"
  ) values (
    current_user_id, 'income', 'Cicilan kredit',
    'Cicilan transaksi ' || coalesce(transaction_row."invoiceNo", '#' || p_transaction_id::text)
      || ' · ' || transaction_row."customerName",
    p_amount, p_transaction_id, p_request_id, operation_time, operation_time, operation_time
  );

  return p_transaction_id;
end;
$$;

