create table if not exists public.products (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  name text not null,
  category text,
  unit text not null default 'pcs',
  price double precision not null default 0,
  price_pcs double precision,
  price_lusin double precision,
  price_kodi double precision,
  cost double precision not null default 0,
  stock integer not null default 0,
  stock_pcs integer not null default 0,
  stock_cost_value double precision not null default 0,
  image_path text,
  "createdAt" timestamptz,
  "updatedAt" timestamptz
);

create table if not exists public.product_categories (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  name text not null,
  "createdAt" timestamptz,
  "updatedAt" timestamptz
);

create table if not exists public.product_units (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  name text not null,
  "createdAt" timestamptz,
  "updatedAt" timestamptz
);

create table if not exists public.customer_names (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  name text not null,
  "createdAt" timestamptz,
  "updatedAt" timestamptz
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  "invoiceNo" text,
  items jsonb not null default '[]'::jsonb,
  total double precision not null default 0,
  payment double precision not null default 0,
  "customerName" text not null default '',
  "paymentType" text not null default 'cash' check ("paymentType" in ('cash', 'credit')),
  "paidAmount" double precision not null default 0,
  "balanceDue" double precision not null default 0,
  payments jsonb not null default '[]'::jsonb,
  "change" double precision not null default 0,
  "requestId" uuid,
  "createdAt" timestamptz,
  "updatedAt" timestamptz
);

create table if not exists public.finance_entries (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  type text not null check (type in ('income', 'expense', 'capital')),
  category text,
  note text,
  amount double precision not null default 0,
  "refId" bigint,
  "requestId" uuid,
  date timestamptz,
  "createdAt" timestamptz,
  "updatedAt" timestamptz
);

create table if not exists public.product_stock_adjustments (
  id bigint generated by default as identity primary key,
  owner_id uuid not null,
  product_id bigint not null,
  product_name text not null,
  quantity_pcs integer not null check (quantity_pcs > 0),
  stock_after_pcs integer not null,
  unit_cost double precision,
  request_id uuid not null,
  "createdAt" timestamptz not null default now()
);

