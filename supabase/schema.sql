create or replace function public.calculate_transaction_gross_profit(p_items jsonb)
returns numeric
language sql
immutable
set search_path = public, pg_temp
as $$
  select coalesce(sum(
    (
      case when coalesce(item.value ->> 'price', '') ~ '^[+-]?[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$'
        then (item.value ->> 'price')::numeric else 0 end
      - case when coalesce(item.value ->> 'cost', '') ~ '^[+-]?[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$'
        then (item.value ->> 'cost')::numeric else 0 end
    )
    * case when coalesce(item.value ->> 'qty', '') ~ '^[+-]?[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$'
        then (item.value ->> 'qty')::numeric else 0 end
  ), 0)
  from jsonb_array_elements(
    case when jsonb_typeof(p_items) = 'array' then p_items else '[]'::jsonb end
  ) as item(value);
$$;

create or replace function public.set_transaction_gross_profit()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.gross_profit := public.calculate_transaction_gross_profit(new.items);
  return new;
end;
$$;

