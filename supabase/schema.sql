create or replace function public.begin_store_backup_restore(p_expected jsonb)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  restore_id uuid := gen_random_uuid();
  expected_key text;
  expected_value jsonb;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if jsonb_typeof(p_expected) <> 'object' then
    raise exception 'Manifest restore bertahap tidak valid.';
  end if;

  foreach expected_key in array array[
    'products', 'categories', 'units', 'customers', 'vendors', 'expeditions',
    'transactions', 'transactionPayments', 'manualCreditPayments', 'finance',
    'manualCredits', 'stockAdjustments'
  ] loop
    expected_value := p_expected -> expected_key;
    if jsonb_typeof(expected_value) <> 'object'
       or coalesce(expected_value ->> 'chunks', '') !~ '^[0-9]+$'
       or coalesce(expected_value ->> 'count', '') !~ '^[0-9]+$' then
      raise exception 'Manifest restore bertahap tidak lengkap.';
    end if;
    if (expected_value ->> 'chunks')::numeric > 2147483647
       or (expected_value ->> 'count')::numeric > 9223372036854775807
       or (expected_value ->> 'chunks')::numeric > (expected_value ->> 'count')::numeric
       or ((expected_value ->> 'count')::numeric = 0 and (expected_value ->> 'chunks')::numeric <> 0)
       or ((expected_value ->> 'count')::numeric > 0 and (expected_value ->> 'chunks')::numeric = 0) then
      raise exception 'Jumlah bagian backup tidak sesuai.';
    end if;
  end loop;

  if (select count(*) from jsonb_object_keys(p_expected)) <> 12 then
    raise exception 'Manifest restore berisi tabel yang tidak dikenal.';
  end if;

  delete from public.store_restore_sessions
  where owner_id = current_user_id
    and "createdAt" < now() - interval '2 days';

  insert into public.store_restore_sessions (owner_id, restore_id, expected)
  values (current_user_id, restore_id, p_expected);
  return restore_id;
end;
$$;

create or replace function public.stage_store_backup_restore_chunk(
  p_restore_id uuid,
  p_table_key text,
  p_chunk_index integer,
  p_records jsonb
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  expected_value jsonb;
  existing_records jsonb;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if jsonb_typeof(p_records) <> 'array' or jsonb_array_length(p_records) < 1
     or jsonb_array_length(p_records) > 100
     or octet_length(p_records::text) > 262144 then
    raise exception 'Bagian data restore tidak valid atau terlalu besar.';
  end if;
  if p_table_key is null or p_table_key not in (
    'products', 'categories', 'units', 'customers', 'vendors', 'expeditions',
    'transactions', 'transactionPayments', 'manualCreditPayments', 'finance',
    'manualCredits', 'stockAdjustments'
  ) then
    raise exception 'Tabel restore tidak dikenal.';
  end if;

  select expected -> p_table_key into expected_value
  from public.store_restore_sessions
  where owner_id = current_user_id and restore_id = p_restore_id
  for update;
  if not found then raise exception 'Sesi restore tidak ditemukan atau sudah kedaluwarsa.'; end if;
  if p_chunk_index is null or p_chunk_index < 0
     or p_chunk_index >= (expected_value ->> 'chunks')::integer then
    raise exception 'Nomor bagian restore tidak valid.';
  end if;
  insert into public.store_restore_chunks (
    owner_id, restore_id, table_key, chunk_index, records
  ) values (
    current_user_id, p_restore_id, p_table_key, p_chunk_index, p_records
  ) on conflict (owner_id, restore_id, table_key, chunk_index) do nothing;

  select records into existing_records
  from public.store_restore_chunks
  where owner_id = current_user_id
    and restore_id = p_restore_id
    and table_key = p_table_key
    and chunk_index = p_chunk_index;
  if existing_records is distinct from p_records then
    raise exception 'Bagian restore duplikat memiliki isi berbeda.';
  end if;
end;
$$;

create or replace function public.commit_store_backup_restore(p_restore_id uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  restore_session public.store_restore_sessions%rowtype;
  current_table_key text;
  expected_value jsonb;
  assembled_records jsonb := '{}'::jsonb;
  assembled_rows jsonb;
  actual_chunks bigint;
  actual_count bigint;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;

  select * into restore_session
  from public.store_restore_sessions
  where owner_id = current_user_id and restore_id = p_restore_id
  for update;
  if not found then raise exception 'Sesi restore tidak ditemukan atau sudah kedaluwarsa.'; end if;

  foreach current_table_key in array array[
    'products', 'categories', 'units', 'customers', 'vendors', 'expeditions',
    'transactions', 'transactionPayments', 'manualCreditPayments', 'finance',
    'manualCredits', 'stockAdjustments'
  ] loop
    expected_value := restore_session.expected -> current_table_key;
    select count(*), coalesce(sum(jsonb_array_length(records)), 0)
    into actual_chunks, actual_count
    from public.store_restore_chunks
    where owner_id = current_user_id
      and restore_id = p_restore_id
      and store_restore_chunks.table_key = current_table_key;

    if actual_chunks <> (expected_value ->> 'chunks')::bigint
       or actual_count <> (expected_value ->> 'count')::bigint then
      raise exception 'Bagian data restore untuk % belum lengkap.', current_table_key;
    end if;

    select coalesce(jsonb_agg(row_value order by chunk.chunk_index, row_item.ordinality), '[]'::jsonb)
    into assembled_rows
    from public.store_restore_chunks chunk
    cross join lateral jsonb_array_elements(chunk.records) with ordinality as row_item(row_value, ordinality)
    where chunk.owner_id = current_user_id
      and chunk.restore_id = p_restore_id
      and chunk.table_key = current_table_key;

    assembled_records := assembled_records || jsonb_build_object(current_table_key, assembled_rows);
  end loop;

  perform public.restore_store_backup(assembled_records);
  delete from public.store_restore_sessions
  where owner_id = current_user_id and restore_id = p_restore_id;
end;
$$;

