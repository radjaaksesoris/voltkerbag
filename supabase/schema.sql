set "paidAmount" = case
      when "paymentType" = 'credit' then least(coalesce(total, 0), coalesce(payment, 0))
      else coalesce(total, 0)
    end,
    "balanceDue" = case
      when "paymentType" = 'credit' then greatest(0, coalesce(total, 0) - coalesce(payment, 0))
      else 0
    end
