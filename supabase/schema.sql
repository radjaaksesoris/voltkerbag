  select * into existing_payment
  from public.vendor_payable_payments
  where owner_id = current_user_id and request_id = p_request_id;
  if found then
    if existing_payment.payable_id is distinct from p_payable_id
       or existing_payment.amount is distinct from p_amount then
      raise exception 'ID permintaan pembayaran utang sudah digunakan.';
    end if;
    return existing_payment.id;
  end if;

  select * into payable_row
  from public.vendor_payables
  where id = p_payable_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Utang pembelian tidak ditemukan.'; end if;
  if p_amount is null or p_amount <= 0
     or p_amount > 9007199254740991::double precision
     or p_amount <> trunc(p_amount)
     or p_amount::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Nominal pembayaran harus rupiah utuh lebih dari Rp0.';
  end if;
  if p_amount > payable_row.balance_due then
    raise exception 'Pembayaran melebihi sisa utang pembelian.';
  end if;

  update public.vendor_payables
  set balance_due = greatest(0, payable_row.balance_due - p_amount),
      "updatedAt" = operation_time
  where id = p_payable_id and owner_id = current_user_id;

  insert into public.vendor_payable_payments (
    owner_id, payable_id, amount, date, request_id
  ) values (
    current_user_id, p_payable_id, p_amount, operation_time, p_request_id
  );

  insert into public.finance_entries (
    owner_id, type, category, note, amount, "refId", "requestId",
    date, "createdAt", "updatedAt"
  ) values (
    current_user_id, 'expense', 'Pembayaran utang pembelian',
    'Pembayaran utang pembelian · ' || payable_row.vendor_name || ' · ' || payable_row.description,
    p_amount, p_payable_id, p_request_id, operation_time, operation_time, operation_time
  );

  return p_payable_id;
end;
