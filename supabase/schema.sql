create or replace function public.get_dashboard_data(
  p_from timestamptz,
  p_to timestamptz,
  p_summary_from timestamptz,
  p_summary_to timestamptz,
  p_page integer,
  p_page_size integer,
  p_credit_first boolean,
  p_name_sort text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  result_count bigint;
  summary_count bigint;
  revenue_total numeric;
  gross_profit numeric;
  transaction_rows jsonb;
  inventory_summary jsonb;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_page is null or p_page < 1 or p_page_size is null or p_page_size < 1 or p_page_size > 100 then
    raise exception 'Halaman transaksi tidak valid.';
  end if;
  if (p_from is not null and p_to is not null and p_from >= p_to)
     or (p_summary_from is not null and p_summary_to is not null and p_summary_from >= p_summary_to) then
    raise exception 'Rentang tanggal tidak valid.';
  end if;
  if coalesce(p_name_sort, 'date') not in ('date', 'asc', 'desc') then
    raise exception 'Urutan nama transaksi tidak valid.';
  end if;

  select count(*), coalesce(sum(t.total), 0),
    coalesce(sum(t.gross_profit), 0)
  into summary_count, revenue_total, gross_profit
  from public.transactions t
  where t.owner_id = current_user_id
    and t."createdAt" >= coalesce(p_summary_from, '-infinity'::timestamptz)
    and t."createdAt" < coalesce(p_summary_to, 'infinity'::timestamptz);

  select count(*)
  into result_count
  from public.transactions t
  where t.owner_id = current_user_id
    and t."createdAt" >= coalesce(p_from, '-infinity'::timestamptz)
    and t."createdAt" < coalesce(p_to, 'infinity'::timestamptz);

  select jsonb_build_object(
    'product_count', count(*),
    'low_stock_count', count(*) filter (
      where coalesce(p.low_stock_threshold, 5) > 0
        and floor(p.stock_pcs::numeric / public.product_unit_factor(p.unit))
          <= coalesce(p.low_stock_threshold, 5)
    ),
    'total_asset', coalesce(sum(p.stock_cost_value), 0)
  )
  into inventory_summary
  from public.products p
  where p.owner_id = current_user_id;

  select coalesce(jsonb_agg(to_jsonb(page_rows) - 'sort_rank'
    order by
      page_rows.sort_rank,
      case when coalesce(p_name_sort, 'date') = 'asc' then lower(trim(page_rows."customerName")) end asc,
      case when coalesce(p_name_sort, 'date') = 'desc' then lower(trim(page_rows."customerName")) end desc,
      page_rows."createdAt" desc nulls last,
      page_rows.id desc
  ), '[]'::jsonb)
  into transaction_rows
  from (
    select t.*,
      case
        when coalesce(p_name_sort, 'date') = 'date'
          and coalesce(p_credit_first, false)
          and t."paymentType" = 'credit'
          and t."balanceDue" > 0
        then 0 else 1
      end as sort_rank
    from public.transactions t
    where t.owner_id = current_user_id
      and t."createdAt" >= coalesce(p_from, '-infinity'::timestamptz)
      and t."createdAt" < coalesce(p_to, 'infinity'::timestamptz)
    order by
      sort_rank,
      case when coalesce(p_name_sort, 'date') = 'asc' then lower(trim(t."customerName")) end asc,
      case when coalesce(p_name_sort, 'date') = 'desc' then lower(trim(t."customerName")) end desc,
      t."createdAt" desc nulls last,
      t.id desc
    limit p_page_size offset (p_page - 1) * p_page_size
  ) as page_rows;

  return jsonb_build_object(
    'transactions', transaction_rows,
    'total_count', result_count,
    'summary_count', summary_count,
    'revenue', revenue_total,
    'gross_profit', gross_profit,
    'inventory', inventory_summary
  );
end;
$$;

create or replace function public.record_expedition_cost(
  p_entry_id bigint,
  p_amount double precision
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  entry_row public.finance_entries%rowtype;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_entry_id is null then raise exception 'Catatan biaya ekspedisi tidak valid.'; end if;
  if p_amount is null or p_amount <= 0
     or p_amount > 9007199254740991::double precision
     or p_amount <> trunc(p_amount)
     or p_amount::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Biaya ekspedisi harus rupiah utuh dalam batas aman.';
  end if;

  select * into entry_row
  from public.finance_entries
  where id = p_entry_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Catatan biaya ekspedisi tidak ditemukan.'; end if;
  if entry_row.type <> 'expense' or entry_row.category not like 'Biaya Ekspedisi %' then
    raise exception 'Catatan ini bukan biaya ekspedisi.';
  end if;
  if not entry_row.pending then
    if entry_row.amount = p_amount then return entry_row.id; end if;
    raise exception 'Biaya ekspedisi ini sudah pernah dilengkapi.';
  end if;

  update public.finance_entries
  set amount = p_amount,
      pending = false,
      "updatedAt" = operation_time
  where id = p_entry_id and owner_id = current_user_id;

  return p_entry_id;
end;
$$;

create or replace function public.get_finance_data(
  p_from timestamptz,
  p_to timestamptz,
  p_page integer,
  p_page_size integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  entry_count bigint;
  entries jsonb;
  income_total numeric;
  expense_total numeric;
  capital_total numeric;
  credit_total numeric;
  credit_balances jsonb;
  gross_profit numeric;
  profit_expense_total numeric;
  pending_expedition_count bigint;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_page is null or p_page < 1 or p_page_size is null or p_page_size < 1 or p_page_size > 100 then
    raise exception 'Halaman buku kas tidak valid.';
  end if;
  if p_from is not null and p_to is not null and p_from >= p_to then
    raise exception 'Rentang tanggal tidak valid.';
  end if;

  select count(*) into pending_expedition_count
  from public.finance_entries
  where owner_id = current_user_id and pending;

  select count(*),
    coalesce(sum(e.amount) filter (where e.type = 'income' and not e.pending), 0),
    coalesce(sum(e.amount) filter (where e.type = 'expense' and not e.pending), 0),
    coalesce(sum(e.amount) filter (where e.type = 'capital' and not e.pending), 0)
  into entry_count, income_total, expense_total, capital_total
  from public.finance_entries e
  where e.owner_id = current_user_id
    and (
      e.pending
      or (
        coalesce(e.date, e."createdAt") >= coalesce(p_from, '-infinity'::timestamptz)
        and coalesce(e.date, e."createdAt") < coalesce(p_to, 'infinity'::timestamptz)
      )
    );

  with outstanding as (
    select
      coalesce(nullif(btrim(t."customerName"), ''), 'Pelanggan lama') as customer_name,
      lower(coalesce(nullif(btrim(t."customerName"), ''), 'Pelanggan lama')) as customer_key,
      t."balanceDue" as balance_due
    from public.transactions t
    where t.owner_id = current_user_id
      and t."paymentType" = 'credit'
      and t."balanceDue" > 0
    union all
    select c.customer_name, lower(btrim(c.customer_name)), c.balance_due
    from public.manual_customer_credits c
    where c.owner_id = current_user_id and c.balance_due > 0
  ), customer_debts as (
    select
      min(outstanding.customer_name) as customer_name,
      outstanding.customer_key,
      sum(outstanding.balance_due) as balance_due
    from outstanding
    group by outstanding.customer_key
  ), customer_payments as (
    select
      lower(btrim(substring(
        entry.note from char_length('Pembayaran umum piutang pelanggan · ') + 1
      ))) as customer_key,
      sum(entry.amount) as paid_amount
    from public.finance_entries entry
    where entry.owner_id = current_user_id
      and entry.type = 'income'
      and entry.category = 'Cicilan kredit'
      and left(entry.note, char_length('Pembayaran umum piutang pelanggan · '))
        = 'Pembayaran umum piutang pelanggan · '
    group by lower(btrim(substring(
      entry.note from char_length('Pembayaran umum piutang pelanggan · ') + 1
    )))
  )
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'customer_name', debt.customer_name,
      'balance_due', greatest(0, debt.balance_due - coalesce(payment.paid_amount, 0))
    ) order by greatest(0, debt.balance_due - coalesce(payment.paid_amount, 0)) desc, debt.customer_name
  ), '[]'::jsonb)
  into credit_balances
  from customer_debts debt
  left join customer_payments payment using (customer_key)
  where greatest(0, debt.balance_due - coalesce(payment.paid_amount, 0)) > 0;

  select coalesce(sum((value->>'balance_due')::numeric), 0)
  into credit_total
  from jsonb_array_elements(credit_balances) as customer(value);

  select coalesce(sum(t.gross_profit), 0)
  into gross_profit
  from public.transactions t
  where t.owner_id = current_user_id
  and t."createdAt" >= coalesce(p_from, '-infinity'::timestamptz)
  and t."createdAt" < coalesce(p_to, 'infinity'::timestamptz);

  select coalesce(sum(e.amount), 0)
  into profit_expense_total
  from public.finance_entries e
  where e.owner_id = current_user_id
    and e.type = 'expense'
    and not e.pending
    and coalesce(e.date, e."createdAt") >= coalesce(p_from, '-infinity'::timestamptz)
    and coalesce(e.date, e."createdAt") < coalesce(p_to, 'infinity'::timestamptz)
    and not (
      (
        lower(trim(coalesce(e.category, ''))) = 'pembelian bahan produksi'
        and position(chr(30) || 'inventory-purchase:' in coalesce(e.note, '')) > 0
      )
      or (
        lower(trim(coalesce(e.category, ''))) = 'pembayaran utang pembelian'
        and exists (
          select 1
          from public.vendor_payables vp
          join public.product_stock_adjustments adjustment
            on adjustment.owner_id = vp.owner_id
           and adjustment.request_id = vp.request_id
          where vp.owner_id = e.owner_id
            and vp.id = e."refId"
        )
      )
    );

  select coalesce(jsonb_agg(to_jsonb(page_rows)
    order by coalesce(page_rows.date, page_rows."createdAt") desc nulls last, page_rows.id desc), '[]'::jsonb)
  into entries
  from (
    select e.*,
      (
        e.type = 'expense'
        and not e.pending
        and not (
          (
            lower(trim(coalesce(e.category, ''))) = 'pembelian bahan produksi'
            and position(chr(30) || 'inventory-purchase:' in coalesce(e.note, '')) > 0
          )
          or (
            lower(trim(coalesce(e.category, ''))) = 'pembayaran utang pembelian'
            and exists (
              select 1
              from public.vendor_payables vp
              join public.product_stock_adjustments adjustment
                on adjustment.owner_id = vp.owner_id
               and adjustment.request_id = vp.request_id
              where vp.owner_id = e.owner_id
                and vp.id = e."refId"
            )
          )
        )
      ) as reduces_profit
    from public.finance_entries e
    where e.owner_id = current_user_id
      and (
        e.pending
        or (
          coalesce(e.date, e."createdAt") >= coalesce(p_from, '-infinity'::timestamptz)
          and coalesce(e.date, e."createdAt") < coalesce(p_to, 'infinity'::timestamptz)
        )
      )
    order by e.pending desc, coalesce(e.date, e."createdAt") desc nulls last, e.id desc
    limit p_page_size offset (p_page - 1) * p_page_size
  ) as page_rows;

  return jsonb_build_object(
    'entries', entries,
    'total_count', entry_count,
    'income', income_total,
    'expense', expense_total,
    'capital', capital_total,
    'pending_expedition_count', pending_expedition_count,
    'total_credit', credit_total,
    'credit_balances', credit_balances,
    'gross_profit', gross_profit,
    'profit_expense', profit_expense_total
  );
end;
$$;

