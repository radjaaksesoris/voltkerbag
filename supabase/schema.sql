create or replace function public.get_finance_data(
  p_from timestamptz,
  p_to timestamptz,
  p_page integer,
  p_page_size integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  entry_count bigint;
  entries jsonb;
  income_total numeric;
  expense_total numeric;
  capital_total numeric;
  credit_total numeric;
  credit_balances jsonb;
  gross_profit numeric;
  pending_expedition_count bigint;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_page is null or p_page < 1 or p_page_size is null or p_page_size < 1 or p_page_size > 100 then
    raise exception 'Halaman buku kas tidak valid.';
  end if;
  if p_from is not null and p_to is not null and p_from >= p_to then
    raise exception 'Rentang tanggal tidak valid.';
  end if;

  select count(*) into pending_expedition_count
  from public.finance_entries
  where owner_id = current_user_id and pending;

  select count(*),
    coalesce(sum(e.amount) filter (where e.type = 'income' and not e.pending), 0),
    coalesce(sum(e.amount) filter (where e.type = 'expense' and not e.pending), 0),
    coalesce(sum(e.amount) filter (where e.type = 'capital' and not e.pending), 0)
  into entry_count, income_total, expense_total, capital_total
  from public.finance_entries e
  where e.owner_id = current_user_id
    and (
      e.pending
      or (
        (p_from is null or coalesce(e.date, e."createdAt") >= p_from)
        and (p_to is null or coalesce(e.date, e."createdAt") < p_to)
      )
    );

  select coalesce(sum(outstanding.balance_due), 0)
  into credit_total
  from (
    select greatest(0, coalesce(t."balanceDue", t.total - coalesce(t."paidAmount", t.payment))) as balance_due
    from public.transactions t
    where t.owner_id = current_user_id and t."paymentType" = 'credit'
    union all
    select c.balance_due
    from public.manual_customer_credits c
    where c.owner_id = current_user_id and c.balance_due > 0
  ) as outstanding;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'customer_name', debt.customer_name,
      'balance_due', debt.balance_due
    ) order by debt.balance_due desc, debt.customer_name
  ), '[]'::jsonb)
  into credit_balances
  from (
    select
      min(outstanding.customer_name) as customer_name,
      sum(outstanding.balance_due) as balance_due
    from (
      select
        coalesce(nullif(btrim(t."customerName"), ''), 'Pelanggan lama') as customer_name,
        lower(coalesce(nullif(btrim(t."customerName"), ''), 'Pelanggan lama')) as customer_key,
        greatest(0, coalesce(t."balanceDue", t.total - coalesce(t."paidAmount", t.payment))) as balance_due
      from public.transactions t
      where t.owner_id = current_user_id and t."paymentType" = 'credit'
      union all
      select c.customer_name, lower(btrim(c.customer_name)), c.balance_due
      from public.manual_customer_credits c
      where c.owner_id = current_user_id and c.balance_due > 0
    ) as outstanding
    group by outstanding.customer_key
    having sum(outstanding.balance_due) > 0
  ) as debt;

  select coalesce(sum((
    select coalesce(sum(
      (coalesce(nullif(item.value ->> 'price', '')::numeric, 0)
        - coalesce(nullif(item.value ->> 'cost', '')::numeric, 0))
      * coalesce(nullif(item.value ->> 'qty', '')::numeric, 0)
    ), 0)
    from jsonb_array_elements(coalesce(t.items, '[]'::jsonb)) as item(value)
  )), 0)
  into gross_profit
  from public.transactions t
  where t.owner_id = current_user_id
    and (p_from is null or t."createdAt" >= p_from)
    and (p_to is null or t."createdAt" < p_to);

  select coalesce(jsonb_agg(to_jsonb(page_rows)
    order by coalesce(page_rows.date, page_rows."createdAt") desc nulls last, page_rows.id desc), '[]'::jsonb)
  into entries
  from (
    select e.*
    from public.finance_entries e
    where e.owner_id = current_user_id
      and (
        e.pending
        or (
          (p_from is null or coalesce(e.date, e."createdAt") >= p_from)
          and (p_to is null or coalesce(e.date, e."createdAt") < p_to)
        )
      )
    order by e.pending desc, coalesce(e.date, e."createdAt") desc nulls last, e.id desc
    limit p_page_size offset (p_page - 1) * p_page_size
  ) as page_rows;

  return jsonb_build_object(
    'entries', entries,
    'total_count', entry_count,
    'income', income_total,
    'expense', expense_total,
    'capital', capital_total,
    'pending_expedition_count', pending_expedition_count,
    'total_credit', credit_total,
    'credit_balances', credit_balances,
    'gross_profit', gross_profit
  );
end;
$$;

