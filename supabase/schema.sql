create or replace function public.complete_sale(
  p_customer_name text,
  p_payment_type text,
  p_payment double precision,
  p_cart jsonb,
  p_request_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  existing_id bigint;
  transaction_id bigint;
  invoice_number text;
  item jsonb;
  product_row public.products%rowtype;
  item_qty integer;
  sale_total double precision := 0;
  saved_items jsonb := '[]'::jsonb;
  initial_payment double precision;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if nullif(trim(p_customer_name), '') is null then raise exception 'Nama pelanggan wajib diisi.'; end if;
  if p_payment_type is null or p_payment_type not in ('cash', 'credit') then
    raise exception 'Metode pembayaran tidak valid.';
  end if;
  if p_payment is null or p_payment < 0 then raise exception 'Nominal pembayaran tidak valid.'; end if;
  if p_request_id is null then raise exception 'ID permintaan transaksi wajib diisi.'; end if;
  if p_cart is null or jsonb_typeof(p_cart) <> 'array' then
    raise exception 'Keranjang masih kosong.';
  end if;
  if jsonb_array_length(p_cart) = 0 then raise exception 'Keranjang masih kosong.'; end if;

  select id into existing_id
  from public.transactions
  where owner_id = current_user_id and "requestId" = p_request_id;
  if existing_id is not null then return existing_id; end if;

  for item in select value from jsonb_array_elements(p_cart)
  loop
    item_qty := (item ->> 'qty')::integer;
    if item_qty <= 0 then raise exception 'Jumlah barang tidak valid.'; end if;

    select * into product_row
    from public.products
    where id = (item ->> 'productId')::bigint and owner_id = current_user_id
    for update;
    if not found then raise exception 'Produk tidak ditemukan atau tidak dapat diakses.'; end if;
    if product_row.stock < item_qty then
      raise exception 'Stok "%" tidak cukup.', product_row.name;
    end if;
    if product_row.price is distinct from (item ->> 'price')::double precision then
      raise exception 'Harga produk "%" berubah. Muat ulang halaman sebelum menyimpan.', product_row.name;
    end if;

    sale_total := sale_total + product_row.price * item_qty;
    saved_items := saved_items || jsonb_build_array(jsonb_build_object(
      'productId', product_row.id,
      'name', product_row.name,
      'unit', product_row.unit,
      'price', product_row.price,
      'cost', product_row.cost,
      'qty', item_qty
    ));
    update public.products
    set stock = stock - item_qty, "updatedAt" = operation_time
    where id = product_row.id and owner_id = current_user_id;
  end loop;

  if p_payment_type = 'cash' and p_payment < sale_total then
    raise exception 'Uang tunai kurang dari total belanja.';
  end if;
  if p_payment_type = 'credit' and p_payment > sale_total then
    raise exception 'Pembayaran awal melebihi total belanja.';
  end if;

  initial_payment := case when p_payment_type = 'cash' then sale_total else p_payment end;
  insert into public.transactions (
    owner_id, items, total, payment, "customerName", "paymentType",
    "paidAmount", "balanceDue", payments, "change", "requestId", "createdAt", "updatedAt"
  ) values (
    current_user_id, saved_items, sale_total, p_payment, trim(p_customer_name), p_payment_type,
    initial_payment, sale_total - initial_payment,
    case when p_payment_type = 'credit' and initial_payment > 0
      then jsonb_build_array(jsonb_build_object('amount', initial_payment, 'date', operation_time))
      else '[]'::jsonb end,
    case when p_payment_type = 'cash' then p_payment - sale_total else 0 end,
    p_request_id, operation_time, operation_time
  ) returning id into transaction_id;

  invoice_number := 'INV-' || to_char(operation_time at time zone 'Asia/Jakarta', 'YYYYMMDD')
    || '-' || lpad(transaction_id::text, 2, '0');
  update public.transactions set "invoiceNo" = invoice_number where id = transaction_id;

  if initial_payment > 0 then
    insert into public.finance_entries (
      owner_id, type, category, note, amount, "refId", date, "createdAt", "updatedAt"
    ) values (
      current_user_id, 'income',
      case when p_payment_type = 'credit' then 'DP kredit' else 'Penjualan' end,
      'Penjualan · ' || trim(p_customer_name), initial_payment, transaction_id,
      operation_time, operation_time, operation_time
    );
  end if;

  return transaction_id;
end;
$$;

create or replace function public.record_transaction_payment(
  p_transaction_id bigint,
  p_amount double precision,
  p_request_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  transaction_row public.transactions%rowtype;
  existing_ref bigint;
  new_paid_amount double precision;
  operation_time timestamptz := clock_timestamp();
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if p_request_id is null then raise exception 'ID permintaan pembayaran wajib diisi.'; end if;
  select * into transaction_row
  from public.transactions
  where id = p_transaction_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Transaksi tidak ditemukan.'; end if;

  select "refId" into existing_ref from public.finance_entries
  where owner_id = current_user_id and "requestId" = p_request_id;
  if existing_ref is not null then
    if existing_ref <> p_transaction_id then raise exception 'ID permintaan pembayaran sudah digunakan.'; end if;
    return existing_ref;
  end if;
  if transaction_row."paymentType" <> 'credit' then
    raise exception 'Cicilan hanya dapat dicatat untuk transaksi kredit.';
  end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Nominal cicilan harus lebih dari Rp0.'; end if;
  if p_amount > transaction_row."balanceDue" then
    raise exception 'Nominal cicilan melebihi sisa utang.';
  end if;

  new_paid_amount := transaction_row."paidAmount" + p_amount;
  update public.transactions
  set "paidAmount" = new_paid_amount,
      "balanceDue" = greatest(0, total - new_paid_amount),
      payments = payments || jsonb_build_array(jsonb_build_object('amount', p_amount, 'date', operation_time)),
      "updatedAt" = operation_time
  where id = p_transaction_id;

  insert into public.finance_entries (
    owner_id, type, category, note, amount, "refId", "requestId", date, "createdAt", "updatedAt"
  ) values (
    current_user_id, 'income', 'Cicilan kredit',
    'Cicilan transaksi ' || coalesce(transaction_row."invoiceNo", '#' || p_transaction_id::text)
      || ' · ' || transaction_row."customerName",
    p_amount, p_transaction_id, p_request_id, operation_time, operation_time, operation_time
  );

  return p_transaction_id;
end;
$$;

revoke all on function public.complete_sale(text, text, double precision, jsonb, uuid) from public, anon;
