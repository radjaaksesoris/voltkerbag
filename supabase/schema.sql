insert into public.product_categories (owner_id, name, "createdAt", "updatedAt")
select distinct p.owner_id, trim(p.category), now(), now()
from public.products p
where p.owner_id is not null and nullif(trim(p.category), '') is not null
on conflict do nothing;

insert into public.product_units (owner_id, name, "createdAt", "updatedAt")
select store_owners.owner_id, defaults.name, now(), now()
from (
  select distinct owner_id from public.products where owner_id is not null
  union
  select id from auth.users
) as store_owners
cross join (values ('pcs'), ('lusin'), ('kodi')) as defaults(name)
on conflict do nothing;

