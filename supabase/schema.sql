do $$
declare
  column_record record;
begin
  for column_record in
    select table_name
    from (values ('products'), ('product_categories'), ('product_units'), ('transactions'), ('finance_entries')) as tables(table_name)
  loop
    if not exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = column_record.table_name
        and column_name = 'id'
        and is_identity = 'YES'
    ) then
      execute format('alter table public.%I alter column id add generated by default as identity', column_record.table_name);
    end if;
  end loop;
end
$$;

update public.transactions
set "paidAmount" = case
      when "paymentType" = 'credit' then least(coalesce(total, 0), coalesce(payment, 0))
      else coalesce(total, 0)
    end,
    "balanceDue" = case
      when "paymentType" = 'credit' then greatest(0, coalesce(total, 0) - coalesce(payment, 0))
      else 0
    end
where "paidAmount" = 0 and coalesce(payment, 0) > 0;

