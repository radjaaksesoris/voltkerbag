insert into public.transaction_payments (
  owner_id, transaction_id, amount, date, source, legacy_key
)
select
  t.owner_id,
  t.id,
  (payment.value ->> 'amount')::double precision,
  coalesce(nullif(payment.value ->> 'date', '')::timestamptz, t."createdAt", now()),
  'legacy',
  'transaction:' || t.id::text || ':payment:' || payment.ordinality::text
from public.transactions t
cross join lateral jsonb_array_elements(
  case when jsonb_typeof(t.payments) = 'array' then t.payments else '[]'::jsonb end
)
  with ordinality as payment(value, ordinality)
where t.owner_id is not null
  and jsonb_typeof(payment.value) = 'object'
  and coalesce(payment.value ->> 'amount', '') ~ '^[0-9]+([.][0-9]+)?$'
  and (payment.value ->> 'amount')::double precision > 0
  and not (
    payment.ordinality = 1
    and exists (
    select 1
    from public.transaction_payments existing_payment
    where existing_payment.owner_id = t.owner_id
      and existing_payment.transaction_id = t.id
      and existing_payment.source = 'initial'
      and existing_payment.amount = (payment.value ->> 'amount')::double precision
      and existing_payment.date = coalesce(
        nullif(payment.value ->> 'date', '')::timestamptz,
        t."createdAt",
        now()
      )
    )
  )
on conflict (owner_id, legacy_key) do nothing;

insert into public.manual_customer_credit_payments (
  owner_id, manual_credit_id, amount, date, legacy_key
)
select
  credit.owner_id,
