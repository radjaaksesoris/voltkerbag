create or replace function public.delete_product_category(p_category_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  category_name text;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;

  select name into category_name
  from public.product_categories
  where id = p_category_id and owner_id = current_user_id
  for update;
  if not found then raise exception 'Kategori tidak ditemukan.'; end if;

  if exists (
    select 1 from public.products
