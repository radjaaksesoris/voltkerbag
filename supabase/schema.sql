create or replace function public.restore_store_backup(p_records jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  table_name text;
  max_id bigint;
  sequence_name text;
begin
  if current_user_id is null then raise exception 'Login diperlukan.'; end if;
  if jsonb_typeof(p_records) <> 'object' then raise exception 'Format data backup tidak valid.'; end if;

  if jsonb_typeof(p_records->'products') <> 'array'
    or jsonb_typeof(p_records->'categories') <> 'array'
    or jsonb_typeof(p_records->'units') <> 'array'
    or jsonb_typeof(p_records->'customers') <> 'array'
    or (p_records ? 'vendors' and jsonb_typeof(p_records->'vendors') <> 'array')
    or (p_records ? 'expeditions' and jsonb_typeof(p_records->'expeditions') <> 'array')
    or jsonb_typeof(p_records->'transactions') <> 'array'
    or (p_records ? 'transactionPayments' and jsonb_typeof(p_records->'transactionPayments') <> 'array')
    or (p_records ? 'manualCreditPayments' and jsonb_typeof(p_records->'manualCreditPayments') <> 'array')
    or (p_records ? 'vendorPayables' and jsonb_typeof(p_records->'vendorPayables') <> 'array')
    or (p_records ? 'vendorPayablePayments' and jsonb_typeof(p_records->'vendorPayablePayments') <> 'array')
    or jsonb_typeof(p_records->'finance') <> 'array'
    or jsonb_typeof(p_records->'stockAdjustments') <> 'array'
    or (p_records ? 'manualCredits' and jsonb_typeof(p_records->'manualCredits') <> 'array') then
    raise exception 'Isi file backup tidak lengkap atau rusak.';
  end if;

  delete from public.product_stock_adjustments where owner_id = current_user_id;
  delete from public.vendor_payable_payments where owner_id = current_user_id;
  delete from public.vendor_payables where owner_id = current_user_id;
  delete from public.manual_customer_credit_payments where owner_id = current_user_id;
  delete from public.manual_customer_credits where owner_id = current_user_id;
  delete from public.finance_entries where owner_id = current_user_id;
  delete from public.transaction_payments where owner_id = current_user_id;
  delete from public.transactions where owner_id = current_user_id;
  delete from public.vendor_names where owner_id = current_user_id;
  delete from public.expedition_names where owner_id = current_user_id;
  delete from public.customer_names where owner_id = current_user_id;
  delete from public.product_categories where owner_id = current_user_id;
  delete from public.product_units where owner_id = current_user_id;
  delete from public.products where owner_id = current_user_id;

  insert into public.products
  select (jsonb_populate_record(null::public.products, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(p_records->'products') as rows(row_data);
  insert into public.product_categories
  select (jsonb_populate_record(null::public.product_categories, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(p_records->'categories') as rows(row_data);
  insert into public.product_units
  select (jsonb_populate_record(null::public.product_units, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(p_records->'units') as rows(row_data);
  insert into public.customer_names
  select (jsonb_populate_record(null::public.customer_names, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(p_records->'customers') as rows(row_data);
  insert into public.vendor_names
  select (jsonb_populate_record(null::public.vendor_names, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(coalesce(p_records->'vendors', '[]'::jsonb)) as rows(row_data);
  insert into public.expedition_names
  select (jsonb_populate_record(null::public.expedition_names, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(coalesce(p_records->'expeditions', '[]'::jsonb)) as rows(row_data);
  insert into public.transactions
  select (jsonb_populate_record(
    null::public.transactions,
    row_data || jsonb_build_object(
      'owner_id', current_user_id,
      'expedition', coalesce(row_data->>'expedition', '')
    )
  )).*
  from jsonb_array_elements(p_records->'transactions') as rows(row_data);
  if p_records ? 'transactionPayments' then
    insert into public.transaction_payments
    select (jsonb_populate_record(
      null::public.transaction_payments,
      row_data || jsonb_build_object('owner_id', current_user_id)
    )).*
    from jsonb_array_elements(p_records->'transactionPayments') as rows(row_data);
  else
    insert into public.transaction_payments (
      owner_id, transaction_id, amount, date, source, legacy_key
    )
    select
      transaction_row.owner_id,
      transaction_row.id,
      (payment.value ->> 'amount')::double precision,
      coalesce(nullif(payment.value ->> 'date', '')::timestamptz, transaction_row."createdAt", now()),
      'legacy',
      'transaction:' || transaction_row.id::text || ':payment:' || payment.ordinality::text
    from public.transactions transaction_row
    cross join lateral jsonb_array_elements(
      case
        when jsonb_typeof(transaction_row.payments) = 'array' then transaction_row.payments
        else '[]'::jsonb
      end
    ) with ordinality as payment(value, ordinality)
    where transaction_row.owner_id = current_user_id
      and jsonb_typeof(payment.value) = 'object'
      and coalesce(payment.value ->> 'amount', '') ~ '^[0-9]+([.][0-9]+)?$'
      and (payment.value ->> 'amount')::double precision > 0
    on conflict (owner_id, legacy_key) do nothing;
  end if;
  insert into public.finance_entries
  select (jsonb_populate_record(
    null::public.finance_entries,
    row_data || jsonb_build_object(
      'owner_id', current_user_id,
      'pending', coalesce((row_data->>'pending')::boolean, false)
    )
  )).*
  from jsonb_array_elements(p_records->'finance') as rows(row_data);
  insert into public.vendor_payables
  select (jsonb_populate_record(
    null::public.vendor_payables,
    row_data || jsonb_build_object('owner_id', current_user_id)
  )).*
  from jsonb_array_elements(coalesce(p_records->'vendorPayables', '[]'::jsonb)) as rows(row_data);
  insert into public.vendor_payable_payments
  select (jsonb_populate_record(
    null::public.vendor_payable_payments,
    row_data || jsonb_build_object('owner_id', current_user_id)
  )).*
  from jsonb_array_elements(coalesce(p_records->'vendorPayablePayments', '[]'::jsonb)) as rows(row_data);
  insert into public.manual_customer_credits
  select (jsonb_populate_record(null::public.manual_customer_credits, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(coalesce(p_records->'manualCredits', '[]'::jsonb)) as rows(row_data);
  if p_records ? 'manualCreditPayments' then
    insert into public.manual_customer_credit_payments
    select (jsonb_populate_record(
      null::public.manual_customer_credit_payments,
      row_data || jsonb_build_object('owner_id', current_user_id)
    )).*
    from jsonb_array_elements(p_records->'manualCreditPayments') as rows(row_data);
  else
    insert into public.manual_customer_credit_payments (
      owner_id, manual_credit_id, amount, date, legacy_key
    )
    select
      credit.owner_id,
      credit.id,
      (payment.value ->> 'amount')::double precision,
      coalesce(nullif(payment.value ->> 'date', '')::timestamptz, credit."createdAt", now()),
      'credit:' || credit.id::text || ':payment:' || payment.ordinality::text
    from public.manual_customer_credits credit
    cross join lateral jsonb_array_elements(
      case when jsonb_typeof(credit.payments) = 'array' then credit.payments else '[]'::jsonb end
    ) with ordinality as payment(value, ordinality)
    where credit.owner_id = current_user_id
      and jsonb_typeof(payment.value) = 'object'
      and coalesce(payment.value ->> 'amount', '') ~ '^[0-9]+([.][0-9]+)?$'
      and (payment.value ->> 'amount')::double precision > 0
    on conflict (owner_id, legacy_key) do nothing;
  end if;
  insert into public.product_stock_adjustments
  select (jsonb_populate_record(null::public.product_stock_adjustments, row_data || jsonb_build_object('owner_id', current_user_id))).*
  from jsonb_array_elements(p_records->'stockAdjustments') as rows(row_data);

  foreach table_name in array array[
    'products', 'product_categories', 'product_units', 'customer_names', 'vendor_names', 'expedition_names',
    'transactions', 'transaction_payments', 'finance_entries',
    'vendor_payables', 'vendor_payable_payments',
    'manual_customer_credits', 'manual_customer_credit_payments',
    'product_stock_adjustments'
  ] loop
    execute format('select max(id) from public.%I', table_name)
      into max_id;
    sequence_name := pg_get_serial_sequence('public.' || table_name, 'id');
    if sequence_name is not null then
      perform setval(sequence_name, coalesce(max_id, 1), max_id is not null);
    end if;
  end loop;
end;
$$;

create or replace function public.bump_store_backup_revision()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  previous_owner uuid;
  next_owner uuid;
begin
  if tg_op <> 'INSERT' then previous_owner := old.owner_id; end if;
  if tg_op <> 'DELETE' then next_owner := new.owner_id; end if;

  if previous_owner is not null then
    insert into public.store_backup_revisions (owner_id, revision)
    values (previous_owner, 1)
    on conflict (owner_id) do update
      set revision = public.store_backup_revisions.revision + 1;
  end if;
  if next_owner is not null and next_owner is distinct from previous_owner then
    insert into public.store_backup_revisions (owner_id, revision)
    values (next_owner, 1)
    on conflict (owner_id) do update
      set revision = public.store_backup_revisions.revision + 1;
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.bump_store_backup_revision() from public, anon, authenticated;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'products', 'product_categories', 'product_units', 'customer_names', 'vendor_names',
    'expedition_names', 'transactions', 'transaction_payments',
    'vendor_payables', 'vendor_payable_payments',
    'manual_customer_credit_payments', 'finance_entries', 'manual_customer_credits',
    'product_stock_adjustments'
  ] loop
    execute format('drop trigger if exists store_backup_revision_changed on public.%I', table_name);
    execute format(
      'create trigger store_backup_revision_changed after insert or update or delete on public.%I '
      'for each row execute function public.bump_store_backup_revision()',
      table_name
    );
  end loop;
end;
$$;

